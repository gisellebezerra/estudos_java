package fundamentos;

public class ConversaoTipoPrimitivo {
	public static void main(String[] args) {
		
		// Decimais
		
		double nota1 = 6; // implícita  
		
		System.out.println(nota1);
		
		float nota2 = (float) 6.8; //explícita
		
		System.out.println(nota2);
		
		//Inteiros
		
		int numero = 10; // implícita
		
		byte convNumero = (byte) numero; //explícita
		
		System.out.println(convNumero);
		
		
		
	}

}
